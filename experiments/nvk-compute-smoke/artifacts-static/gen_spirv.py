#!/usr/bin/env python3
"""Clean-room SPIR-V 1.0 generator for c[i] = a[i] + b[i], plus a no-op control.

No external compiler and no vendor tooling: the opcode numbers were read from
the public Khronos SPIRV-Headers spirv.hpp11
(SHA-256 7454207c6a2de60c008c3c739021ffe667b90317d030694387868ff92293e9ff).
The emitted module is a hand-written instruction stream, not copied bytecode.
"""
import struct
import sys

MAGIC = 0x07230203
VERSION = 0x00010000

# Opcode numbers (SPIRV-Headers)
OP_MEMORY_MODEL = 14
OP_ENTRY_POINT = 15
OP_EXECUTION_MODE = 16
OP_CAPABILITY = 17
OP_TYPE_VOID = 19
OP_TYPE_INT = 21
OP_TYPE_VECTOR = 23
OP_TYPE_RUNTIME_ARRAY = 29
OP_TYPE_STRUCT = 30
OP_TYPE_POINTER = 32
OP_TYPE_FUNCTION = 33
OP_CONSTANT = 43
OP_FUNCTION = 54
OP_FUNCTION_END = 56
OP_VARIABLE = 59
OP_LOAD = 61
OP_STORE = 62
OP_ACCESS_CHAIN = 65
OP_DECORATE = 71
OP_MEMBER_DECORATE = 72
OP_COMPOSITE_EXTRACT = 81
OP_IADD = 128
OP_LABEL = 248
OP_RETURN = 253

# Enum values
CAP_SHADER = 1
MEMORY_MODEL_LOGICAL = 0
MEMORY_MODEL_GLSL450 = 1
EXEC_GLCOMPUTE = 5
EXEC_MODE_LOCAL_SIZE = 17
DEC_BLOCK = 2
DEC_ARRAY_STRIDE = 6
DEC_OFFSET = 35
DEC_BUILTIN = 11
DEC_BINDING = 33
DEC_DESCRIPTOR_SET = 34
BUILTIN_GLOBAL_INVOCATION_ID = 28
SC_INPUT = 1
SC_STORAGE_BUFFER = 12
LOCAL_SIZE = 64


def inst(op, *operands):
    return [(len(operands) + 1) << 16 | op] + list(operands)


def string_words(s):
    data = s.encode() + b"\0"
    data += b"\0" * ((4 - len(data) % 4) % 4)
    return list(struct.unpack("<%dI" % (len(data) // 4), data))


def emit(words, out_name, label):
    with open(out_name, "w") as f:
        f.write("/* Generated by gen_spirv.py -- %s — do not edit by hand. */\n" % label)
        f.write("static const uint32_t vector_add_spirv[] = {\n")
        for i in range(0, len(words), 8):
            f.write("    " + ", ".join("0x%08xU" % w for w in words[i:i + 8]) + ",\n")
        f.write("};\n")
        f.write("static const size_t vector_add_spirv_words = %dU;\n" % len(words))
    print("SPIRV-%s WORDS=%d" % (label, len(words)))


def emit_noop():
    """Valid GLCompute entry point that does not write C: negative control only."""
    fn_main, label, void, fn_void = 5, 6, 1, 2
    words = [MAGIC, VERSION, 0, 7, 0]
    words += inst(OP_CAPABILITY, CAP_SHADER)
    words += inst(OP_MEMORY_MODEL, MEMORY_MODEL_LOGICAL, MEMORY_MODEL_GLSL450)
    words += inst(OP_ENTRY_POINT, EXEC_GLCOMPUTE, fn_main, *string_words("main"))
    words += inst(OP_EXECUTION_MODE, fn_main, EXEC_MODE_LOCAL_SIZE, LOCAL_SIZE, 1, 1)
    words += inst(OP_TYPE_VOID, void)
    words += inst(OP_TYPE_FUNCTION, fn_void, void)
    words += inst(OP_FUNCTION, void, fn_main, 0, fn_void)
    words += inst(OP_LABEL, label)
    words += inst(OP_RETURN)
    words += inst(OP_FUNCTION_END)
    emit(words, "shader_noop.spv.h", "NOOP")


def main():
    # SSA ids
    void, fn_void, uint = 1, 2, 3
    c64, c0 = 4, 5
    rt_array, struct_ab, ptr_ab, var_a = 6, 7, 8, 9
    struct_bb, ptr_bb, var_b = 10, 11, 12
    struct_cc, ptr_cc, var_c = 13, 14, 15
    ptr_uint_sb, v3uint, ptr_v3_in, var_gid = 16, 17, 18, 19
    fn_main, label = 20, 21
    r_gid, r_i, r_apid, r_av, r_bpid, r_bv, r_sum, r_cpid = range(22, 30)
    bound = 30

    words = [MAGIC, VERSION, 0, bound, 0]
    words += inst(OP_CAPABILITY, CAP_SHADER)
    words += inst(OP_MEMORY_MODEL, MEMORY_MODEL_LOGICAL, MEMORY_MODEL_GLSL450)
    words += inst(OP_ENTRY_POINT, EXEC_GLCOMPUTE, fn_main, *string_words("main"),
                  var_a, var_b, var_c, var_gid)
    words += inst(OP_EXECUTION_MODE, fn_main, EXEC_MODE_LOCAL_SIZE, LOCAL_SIZE, 1, 1)

    for var, binding in ((var_a, 0), (var_b, 1), (var_c, 2)):
        words += inst(OP_DECORATE, var, DEC_DESCRIPTOR_SET, 0)
        words += inst(OP_DECORATE, var, DEC_BINDING, binding)
    for block in (struct_ab, struct_bb, struct_cc):
        words += inst(OP_DECORATE, block, DEC_BLOCK)
        words += inst(OP_MEMBER_DECORATE, block, 0, DEC_OFFSET, 0)
    words += inst(OP_DECORATE, rt_array, DEC_ARRAY_STRIDE, 4)
    words += inst(OP_DECORATE, var_gid, DEC_BUILTIN, BUILTIN_GLOBAL_INVOCATION_ID)

    words += inst(OP_TYPE_VOID, void)
    words += inst(OP_TYPE_FUNCTION, fn_void, void)
    words += inst(OP_TYPE_INT, uint, 32, 0)
    words += inst(OP_CONSTANT, uint, c64, LOCAL_SIZE)
    words += inst(OP_CONSTANT, uint, c0, 0)
    words += inst(OP_TYPE_RUNTIME_ARRAY, rt_array, uint)
    words += inst(OP_TYPE_STRUCT, struct_ab, rt_array)
    words += inst(OP_TYPE_POINTER, ptr_ab, SC_STORAGE_BUFFER, struct_ab)
    words += inst(OP_VARIABLE, ptr_ab, var_a, SC_STORAGE_BUFFER)
    words += inst(OP_TYPE_STRUCT, struct_bb, rt_array)
    words += inst(OP_TYPE_POINTER, ptr_bb, SC_STORAGE_BUFFER, struct_bb)
    words += inst(OP_VARIABLE, ptr_bb, var_b, SC_STORAGE_BUFFER)
    words += inst(OP_TYPE_STRUCT, struct_cc, rt_array)
    words += inst(OP_TYPE_POINTER, ptr_cc, SC_STORAGE_BUFFER, struct_cc)
    words += inst(OP_VARIABLE, ptr_cc, var_c, SC_STORAGE_BUFFER)
    words += inst(OP_TYPE_POINTER, ptr_uint_sb, SC_STORAGE_BUFFER, uint)
    words += inst(OP_TYPE_VECTOR, v3uint, uint, 3)
    words += inst(OP_TYPE_POINTER, ptr_v3_in, SC_INPUT, v3uint)
    words += inst(OP_VARIABLE, ptr_v3_in, var_gid, SC_INPUT)

    words += inst(OP_FUNCTION, void, fn_main, 0, fn_void)
    words += inst(OP_LABEL, label)
    words += inst(OP_LOAD, v3uint, r_gid, var_gid)
    words += inst(OP_COMPOSITE_EXTRACT, uint, r_i, r_gid, 0)
    words += inst(OP_ACCESS_CHAIN, ptr_uint_sb, r_apid, var_a, c0, r_i)
    words += inst(OP_LOAD, uint, r_av, r_apid)
    words += inst(OP_ACCESS_CHAIN, ptr_uint_sb, r_bpid, var_b, c0, r_i)
    words += inst(OP_LOAD, uint, r_bv, r_bpid)
    words += inst(OP_IADD, uint, r_sum, r_av, r_bv)
    words += inst(OP_ACCESS_CHAIN, ptr_uint_sb, r_cpid, var_c, c0, r_i)
    words += inst(OP_STORE, r_cpid, r_sum)
    words += inst(OP_RETURN)
    words += inst(OP_FUNCTION_END)

    emit(words, "shader.spv.h", "VECTOR-ADD")
    print("BOUND=%d" % bound)


if __name__ == "__main__":
    if len(sys.argv) == 2 and sys.argv[1] == "--noop":
        emit_noop()
    elif len(sys.argv) == 1:
        main()
    else:
        raise SystemExit("usage: gen_spirv.py [--noop]")
