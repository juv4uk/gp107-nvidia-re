#!/usr/bin/env bash
# Твердження про інший репозиторій мусить бути прив'язане до зрізу.
#
# Привід конкретний: цей репозиторій двічі цитував wsm-desktop без жодного
# коміту, і обидва рази формулювання вже встигло застаріти. Найгірший випадок —
# твердження «suspend обслуговується пропрієтарним модулем, отже закритий», яке
# сусідній репозиторій сам спростував: це заява про драйвер, а не про машину.
#
# Правило: якщо документ згадує wsm-desktop (або інший зовнішній репозиторій із
# переліку нижче) як джерело факту, у тому самому абзаці має бути зріз —
# `repo@<sha>` або посилання на конкретний commit/blob із 7+ hex.
#
# Перевірка навмисно вузька: вона не судить, чи твердження правильне. Вона
# ловить лише «цитата без дати», бо саме така цитата тихо стає хибною.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

fail() { echo "CROSS-REPO-PIN-FAIL: $*" >&2; exit 2; }
note() { echo "cross-repo-pin: $*"; }

# Зовнішні репозиторії, посилання на які ми зобов'язані пінити.
#
# Перевіряємо саме ПОСИЛАННЯ, а не будь-яку згадку. «Pin-и v8/v9 не змінено» —
# це твердження про цей репозиторій, і пін там зайвий; «див. wsm-desktop/docs/…» —
# це цитата чужого факту, і без зрізу вона тихо старіє.
EXTERNAL_RE="github\.com/juv4uk/(wsm-desktop|wsm-os-lisp|wsm-lazarus)"

shopt -s nullglob
docs=(docs/*.md README.md)
[ "${#docs[@]}" -gt 0 ] || fail "немає документів; перевірка пройшла б порожньо"

# Зріз у абзаці: repo@sha, або /blob/<sha>/ чи /commit/<sha>, або «зріз `sha`».
PIN_RE='(@[0-9a-f]{7,40}|/blob/[0-9a-f]{7,40}|/commit/[0-9a-f]{7,40}|[0-9a-f]{7,40}[`’'"'"' ])'

checked=0
problems=0

for doc in "${docs[@]}"; do
  [ -f "$doc" ] || continue
  # Абзаци розділяємо порожнім рядком; цього досить, бо всі наші твердження
  # про інші репозиторії сформульовані в межах одного абзацу або пункту списку.
  while IFS= read -r -d '' paragraph; do
    if printf '%s' "$paragraph" | grep -qE "$EXTERNAL_RE"; then
      checked=$((checked + 1))
      if ! printf '%s' "$paragraph" | grep -qE "$PIN_RE"; then
        first_line="$(printf '%s' "$paragraph" | head -1 | cut -c1-90)"
        printf '%s: абзац посилається на зовнішній репозиторій без зрізу — %s…\n' \
          "$doc" "$first_line" >&2
        problems=$((problems + 1))
      fi
    fi
  done < <(awk 'BEGIN { RS=""; ORS="\0" } { print }' "$doc")
done

[ "$checked" -gt 0 ] || fail "у документах немає жодного посилання на зовнішній репозиторій; перевірка нічого не доводить"

if [ "$problems" -ne 0 ]; then
  fail "$problems абзаців посилаються на зовнішній репозиторій без зрізу"
fi

note "$checked абзаців посилаються на зовнішній репозиторій, усі прив'язані до зрізу"
